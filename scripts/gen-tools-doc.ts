// Regenerates docs/TOOLS.md from the registered tools: npm run docs:tools
import fs from 'node:fs';
import { loadConfig } from '../src/config.js';
import { SCENARIOS } from '../src/prompts/index.js';
import { SCENARIOS as RUNBOOKS } from '../src/scenarios/index.js';
import { createServer } from '../src/server.js';
import { registry } from '../src/tools/helpers.js';

createServer(loadConfig({ MIA_INVENTORY: '/nonexistent', MIA_STATE_DIR: '/tmp/mia-doc' }));

const groups: Array<[string, string[]]> = [
    ['Fleet', ['fleet_hosts', 'fleet_discover', 'fleet_status', 'fleet_audit']],
    ['One host', ['host_inspect', 'host_logs', 'host_ports', 'host_firewall', 'host_docker', 'host_file_read', 'host_net_check', 'tuning_status']],
    ['Changes and history', ['fleet_snapshot', 'fleet_changes', 'snapshots_list', 'journal_list', 'job_status']],
    ['Services', ['service_action', 'remnanode_update']],
    ['Node maintenance', ['cert_renew', 'geo_update', 'blacklist_update', 'updates_policy', 'apt_upgrade', 'host_reboot', 'disk_cleanup', 'tuning_apply']],
    ['Firewall', ['ufw_rule', 'fail2ban_unban']],
    ['Home services and media', ['host_services_discover', 'jellyfin_status', 'jellyfin_library_add_path', 'jellyfin_library_create', 'jellyfin_scan', 'jellyfin_task_run', 'tdarr_status', 'tdarr_library_add', 'tdarr_scan', 'tdarr_pause']],
    ['Provisioning', ['node_bootstrap']],
    ['Escape hatch', ['host_exec']],
];

const seen = new Set(groups.flatMap(([, t]) => t));
const missing = [...registry.keys()].filter((t) => !seen.has(t));
if (missing.length) groups.push(['Other', missing]);

const ro = [...registry.values()].filter((t) => t.readonly).length;
const lines = [
    '# Tools',
    '',
    `Generated by \`npm run docs:tools\`: ${registry.size} tools, ${ro} of them read-only (✓ in the RO column). With \`MIA_READONLY=true\` the others stay listed but refuse \`apply\`.`,
    '',
    'Every tool without ✓ is two-step: without `apply` it returns the plan per host and a `planHash`; the same call with `apply: true, planHash` runs it.',
    '',
];
for (const [title, tools] of groups) {
    lines.push(`## ${title}`, '', '| Tool | RO | What it does |', '|---|---|---|');
    for (const name of tools) {
        const t = registry.get(name);
        if (!t) throw new Error(`doc lists unknown tool ${name}`);
        lines.push(`| \`${name}\` | ${t.readonly ? '✓' : ''} | ${t.description.replace(/\|/g, '\\|')} |`);
    }
    lines.push('');
}
lines.push('## Prompts (scenarios)', '', '| Prompt | What it does |', '|---|---|');
for (const s of SCENARIOS) lines.push(`| \`${s.name}\` | ${s.description} |`);
lines.push('');

fs.mkdirSync('docs', { recursive: true });
fs.writeFileSync('docs/TOOLS.md', lines.join('\n'));
// the README table carries the same numbers: keep them from drifting
const readme = fs.readFileSync('README.md', 'utf8')
    .replace(/\| Инструменты \| \d+ \(\d+ только чтение\)/, `| Инструменты | ${registry.size} (${ro} только чтение)`)
    .replace(/(\| Ранбуки \| `mia scenario …`: )[^—]+—/, `$1${[...RUNBOOKS.keys()].join(', ')} —`);
fs.writeFileSync('README.md', readme);
console.log(`docs/TOOLS.md, README.md: ${registry.size} tools, ${RUNBOOKS.size} runbooks`);
